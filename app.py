def _fmt_time(s: float) -> str:
    m, sec = divmod(abs(s), 60)
    return f"{int(m)}:{sec:04.1f}"


def _video_mime(path: str) -> str:
    return {".mov": "video/quicktime", ".mp4": "video/mp4"}.get(
        os.path.splitext(path)[1].lower(), "video/mp4"
    )


def _waveform_section(audio_path: str, audio_duration: float, loop_interval: float) -> None:
    """
    Show a waveform PNG (generated by FFmpeg once, then cached) with red vertical
    markers at every video-loop boundary, so the user can see where the music beat
    falls relative to each loop point.
    """
    wv_id = os.path.splitext(os.path.basename(audio_path))[0]
    wv_png = os.path.join(UPLOAD_DIR, f"wv_{wv_id}.png")

    if not os.path.exists(wv_png):
        with st.spinner("Generating waveform…"):
            try:
                engine.generate_waveform_png(audio_path, wv_png)
            except engine.AutoLoopError as exc:
                st.warning(f"Waveform unavailable: {exc}")
                return

    try:
        img = Image.open(wv_png).convert("RGBA")
    except Exception as exc:
        st.warning(f"Could not open waveform image: {exc}")
        return

    w, h = img.size
    overlay = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    draw = ImageDraw.Draw(overlay)

    n_loops = int(audio_duration / loop_interval) if loop_interval > 0 else 0
    px_per_loop = w * loop_interval / audio_duration if audio_duration > 0 else w
    # Skip markers that would overlap — enforce ≥ 20px gap between lines
    step = max(1, math.ceil(20 / px_per_loop))
    show_labels = px_per_loop >= 50

    for i in range(step, n_loops + 1, step):
        t = i * loop_interval
        if t > audio_duration + 0.001:
            break
        x = max(1, min(w - 2, int(t / audio_duration * (w - 1))))
        draw.line([(x, 0), (x, h)], fill=(255, 80, 80, 210), width=2)
        if show_labels:
            m_t, s_t = divmod(t, 60)
            draw.text((x + 3, 3), f"{int(m_t)}:{s_t:04.1f}", fill=(255, 210, 210, 220))

    result = Image.alpha_composite(img, overlay).convert("RGB")
    st.image(result, use_container_width=True)

    n_full = int(audio_duration / loop_interval) if loop_interval > 0 else 0
    tail = audio_duration - n_full * loop_interval
    tail_str = f" + {tail:.2f}s tail" if tail > 0.05 else ""
    st.caption(
        f"↻ = video restarts every **{loop_interval:.2f}s**  ·  "
        f"**{n_full}** full cycle(s){tail_str} within this audio track"
    )

