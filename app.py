    _ep_c2.metric("File size", sel_preset.size_label)
    _ep_c3.metric("Compatibility", sel_preset.compat_label)
    st.caption(sel_preset.description)

    enc_crf: int | None = None
    if enc_preset_id == "h264":
        _h264_ql = st.select_slider(
            "H.264 quality",
            options=["Smaller file (CRF 28)", "Balanced (CRF 23)", "High quality (CRF 18)"],
            value="Balanced (CRF 23)",
            key="enc_crf_h264",
        )
        enc_crf = {"Smaller file (CRF 28)": 28, "Balanced (CRF 23)": 23, "High quality (CRF 18)": 18}[_h264_ql]
    elif enc_preset_id == "h265":
        _h265_ql = st.select_slider(
            "H.265 quality",
            options=["Smaller file (CRF 32)", "Balanced (CRF 28)", "High quality (CRF 24)"],
            value="Balanced (CRF 28)",
            key="enc_crf_h265",
        )
        enc_crf = {"Smaller file (CRF 32)": 32, "Balanced (CRF 28)": 28, "High quality (CRF 24)": 24}[_h265_ql]

    if effective_video_path is not None and enc_preset_id != "copy":
        _evp_id = os.path.splitext(os.path.basename(effective_video_path))[0]
        _enc_crf_str = str(enc_crf) if enc_crf is not None else "default"
        _enc_key = f"enc_{enc_preset_id}_{_enc_crf_str}_{_evp_id}"
        _enc_path = os.path.join(UPLOAD_DIR, f"{_enc_key}{sel_preset.ext}")
        if _enc_key not in st.session_state or not os.path.exists(_enc_path):
            with st.spinner(f"Re-encoding loop unit to {sel_preset.label}…"):
                try:
                    engine.create_encode_unit(effective_video_path, _enc_path, enc_preset_id, enc_crf)
                    st.session_state[_enc_key] = _enc_path
                except engine.AutoLoopError as e:
                    st.error(str(e))
                    st.stop()
        try:
            effective_video_info = engine.probe_video(_enc_path)
            effective_video_path = _enc_path
        except engine.InvalidVideoError as e:
            st.error(f"Encode unit corrupted — re-upload the source clip. ({e})")
            st.stop()
        if enc_preset_id != "prores":
            st.success(f"Loop unit re-encoded: **{sel_preset.label}** — audio stripped, add music below if needed.")
        else:
            st.success(f"Loop unit re-encoded: **{sel_preset.label}** · output will be .mov")

    # --- 2. Duration ------------------------------------------------------------------------
    st.subheader("2. Target output duration")
    duration_mode = st.radio(
        "How should the output duration be decided?",
        ["Set manually (H/M/S)", "Match accompanying audio file(s)"],
        horizontal=True,
    )

    # manual_target_seconds: single int, used only in manual mode.
    # audio_batch: list[engine.AudioBatchItem], used only in audio mode (1+ files = batch).
    manual_target_seconds = None
    manual_audio_path = None  # background music for manual mode (loops independently)
    duration_error = None
    audio_batch: list = []

    if duration_mode == "Set manually (H/M/S)":
        d1, d2, d3 = st.columns(3)
        hours = d1.number_input("Hours", min_value=0, max_value=engine.MAX_TARGET_HOURS, value=10, step=1)
        minutes = d2.number_input("Minutes", min_value=0, max_value=59, value=0, step=1)
        seconds = d3.number_input("Seconds", min_value=0, max_value=59, value=0, step=1)

        try:
            manual_target_seconds = engine.compute_total_seconds(hours, minutes, seconds)
        except engine.InvalidDurationError as e:
            duration_error = str(e)

        st.caption("Background music — optional. Audio loops independently alongside the video loop.")
        bg_audio_file = st.file_uploader(
            "Background music (optional)",
            type=[ext.lstrip(".") for ext in sorted(engine.ALLOWED_AUDIO_EXTENSIONS)],
            key="bg_audio_uploader",
        )

        if bg_audio_file is not None:
            try:
                bg_audio_ext = engine.validate_audio_extension(bg_audio_file.name)

                if "bg_audio_tokens" not in st.session_state:
                    st.session_state["bg_audio_tokens"] = {}
                bg_token_key = f"{bg_audio_file.name}:{bg_audio_file.size}"
                if bg_token_key not in st.session_state["bg_audio_tokens"]:
                    st.session_state["bg_audio_tokens"][bg_token_key] = uuid.uuid4().hex[:10]
                bg_token = st.session_state["bg_audio_tokens"][bg_token_key]

                bg_audio_path = os.path.join(UPLOAD_DIR, f"bg_{bg_token}{bg_audio_ext}")
                if not os.path.exists(bg_audio_path):
                    os.makedirs(UPLOAD_DIR, exist_ok=True)
                    with open(bg_audio_path, "wb") as f:
                        f.write(bg_audio_file.getbuffer())

                bg_audio_info = engine.probe_audio(bg_audio_path)
                manual_audio_path = bg_audio_path

                if manual_target_seconds:
                    audio_loops = manual_target_seconds / bg_audio_info.duration_seconds
                    st.info(
                        f"**{bg_audio_file.name}** · {_fmt_time(bg_audio_info.duration_seconds)} "
                        f"({bg_audio_info.duration_seconds:.1f}s)  —  "
                        f"will loop **{audio_loops:.1f}×** to fill the target duration."
                    )
                if effective_video_info is not None:
                    _waveform_section(
                        bg_audio_path,
                        bg_audio_info.duration_seconds,
                        effective_video_info.duration_seconds,
                    )
            except engine.AutoLoopError as e:
                st.error(f"Background audio rejected: {e}")

    else:
        uploaded_audios = st.file_uploader(
            "MP3, WAV, M4A, AAC, FLAC, OGG, or WMA — pick one file for a single render, or "
            "several for a batch. Each output is looped/trimmed to exactly that file's length, "
            "with that audio replacing the source video's own soundtrack.",
            type=[ext.lstrip(".") for ext in sorted(engine.ALLOWED_AUDIO_EXTENSIONS)],
            accept_multiple_files=True,
            key="audio_uploader",
        )

        if "audio_tokens" not in st.session_state:
            st.session_state["audio_tokens"] = {}

        if uploaded_audios:
            rows = []
            for uf in uploaded_audios:
                try:
                    audio_ext = engine.validate_audio_extension(uf.name)
                except engine.InvalidAudioError as e:
                    rows.append({"File": uf.name, "Duration": "-", "Status": f"rejected: {e}"})
                    continue

                token_key = f"{uf.name}:{uf.size}"
                if token_key not in st.session_state["audio_tokens"]:
                    st.session_state["audio_tokens"][token_key] = uuid.uuid4().hex[:10]
                token = st.session_state["audio_tokens"][token_key]

                audio_path = os.path.join(UPLOAD_DIR, f"{token}{audio_ext}")
                if not os.path.exists(audio_path):
                    with open(audio_path, "wb") as f:
                        f.write(uf.getbuffer())

                try:
                    audio_info = engine.probe_audio(audio_path)
                    target = engine.validate_duration_seconds(audio_info.duration_seconds)
                    audio_batch.append(
                        engine.AudioBatchItem(
                            display_name=uf.name,
                            audio_path=audio_path,
                            audio_info=audio_info,
                            target_seconds=target,
                        )
                    )
                    rows.append({"File": uf.name, "Duration": f"{target:.2f}s", "Status": "ready"})
                except engine.AutoLoopError as e:
                    rows.append({"File": uf.name, "Duration": "-", "Status": f"rejected: {e}"})

            st.table(rows)
            if not audio_batch:
                duration_error = "None of the uploaded audio files were usable — fix or replace them above."
            elif effective_video_info is not None:
                _wv_item = audio_batch[0]
                if len(audio_batch) > 1:
                    _wv_name = st.selectbox(
                        "Waveform",
                        [x.display_name for x in audio_batch],
                        key="wv_track_sel",
                        label_visibility="collapsed",
                    )
                    _wv_item = next(x for x in audio_batch if x.display_name == _wv_name)
                _waveform_section(
                    _wv_item.audio_path,
                    _wv_item.audio_info.duration_seconds,
                    effective_video_info.duration_seconds,
                )
        else:
            duration_error = "Upload at least one audio file to use as the duration source."

    if duration_error:
        st.warning(duration_error)

    # --- 2b. Audio settings (volume + fade) — shown only when output will have audio ----------
    _has_audio_output = (
        (duration_mode == "Set manually (H/M/S)" and manual_audio_path is not None)
        or (duration_mode != "Set manually (H/M/S)" and bool(audio_batch))
    )

    audio_volume = 1.0
    audio_fade_in = 0.0
    audio_fade_out = 0.0

    if _has_audio_output:
        with st.expander("🔊 Audio settings", expanded=False):
            audio_volume = st.slider(
                "Volume", min_value=0, max_value=200, value=100, step=5, format="%d%%"
            ) / 100.0

            fa_col, fo_col = st.columns(2)
            audio_fade_in = fa_col.slider(
                "Fade-in", min_value=0.0, max_value=60.0, value=0.0, step=0.5, format="%.1fs"
            )
            audio_fade_out = fo_col.slider(
                "Fade-out", min_value=0.0, max_value=60.0, value=0.0, step=0.5, format="%.1fs"
            )

            if audio_fade_in > 0 or audio_fade_out > 0:
                if duration_mode == "Set manually (H/M/S)" and manual_target_seconds:
                    if audio_fade_in + audio_fade_out >= manual_target_seconds:
                        st.warning(
                            f"Fade-in ({audio_fade_in:.1f}s) + Fade-out ({audio_fade_out:.1f}s) "
                            f"exceeds the target duration ({manual_target_seconds}s)."
                        )
                elif audio_batch:
                    shortest = min(item.target_seconds for item in audio_batch)
                    if audio_fade_in + audio_fade_out >= shortest:
                        st.warning(
                            f"Fade-in + Fade-out ({audio_fade_in + audio_fade_out:.1f}s total) "
                            f"exceeds the shortest audio track ({shortest:.1f}s). Reduce fade durations."
                        )

    # --- 3. Estimate & confirm ---------------------------------------------------------------
    # render_jobs: list of (label, target_seconds, audio_path_or_None, loop_audio_bool)
    # loop_audio=True  → render_looped_video_with_looped_audio (both streams loop)
    # loop_audio=False → render_looped_video_with_audio (audio plays once, target = audio duration)
    render_jobs = []
    if video_info is not None:
        if duration_mode == "Set manually (H/M/S)" and manual_target_seconds:
            render_jobs = [(uploaded_file.name, manual_target_seconds, manual_audio_path, True)]
        elif duration_mode != "Set manually (H/M/S)" and audio_batch:
            render_jobs = [
                (item.display_name, item.target_seconds, item.audio_path, False)
                for item in audio_batch
            ]

    proceed = False
    confirmed_large = True

    if render_jobs:
        total_estimated_bytes = sum(
            engine.estimate_output_size_bytes(effective_video_info, secs)
            + (int(24 * 1024 * secs) if ap else 0)  # 192 kbps AAC when audio is present
            for _, secs, ap, _ in render_jobs
        )
        if len(render_jobs) == 1:
            loop_count = render_jobs[0][1] / effective_video_info.duration_seconds
            if boomerang_enabled and crossfade_enabled:
                unit_desc, unit_label = "boomerang + crossfade unit", "boomerang+crossfade cycle"
            elif boomerang_enabled:
                unit_desc, unit_label = "boomerang unit", "boomerang cycle"
            elif crossfade_enabled:
                unit_desc, unit_label = "crossfade unit", "crossfade cycle"
            else:
                unit_desc, unit_label = "source", "loop"
            st.write(
                f"Will repeat the {unit_desc} **{loop_count:,.1f}x** ({unit_label}) "
                f"→ estimated output size **{engine.format_bytes(total_estimated_bytes)}**"
            )
        else:
            st.write(
                f"Batch of **{len(render_jobs)}** outputs → estimated total size "
                f"**{engine.format_bytes(total_estimated_bytes)}**"
            )

        try:
            engine.ensure_disk_space(OUTPUT_DIR, total_estimated_bytes)
            proceed = True
        except engine.InsufficientDiskSpaceError as e:
            st.error(str(e))
            proceed = False

        if proceed and total_estimated_bytes > LARGE_OUTPUT_WARN_BYTES:
            confirmed_large = st.checkbox(
                f"This will write roughly {engine.format_bytes(total_estimated_bytes)} to disk in total. "
                "I understand and want to proceed."
            )

    # --- 4. Render --------------------------------------------------------------------------
    st.subheader("3. Render")
    render_label = "Render Looped Video" if len(render_jobs) <= 1 else f"Render Batch ({len(render_jobs)} files)"
    render_clicked = st.button(
        render_label,
        disabled=not (render_jobs and proceed and confirmed_large),
        type="primary",
    )

    if render_clicked:
        results = []
        progress_bar = st.progress(0.0)
        status = st.empty()
        start = time.time()

        _out_ext = None if enc_preset_id == "copy" else sel_preset.ext
        if duration_mode == "Set manually (H/M/S)":
            label, secs, audio_p, loop_audio = render_jobs[0]
            status.write(f"Rendering: **{label}**")
            output_path = engine.build_output_path(OUTPUT_DIR, uploaded_file.name, output_ext=_out_ext)
            try:
                if audio_p is None:
                    engine.render_looped_video(effective_video_path, output_path, secs)
                else:
                    engine.render_looped_video_with_looped_audio(
                        effective_video_path, audio_p, output_path, secs,
                        volume=audio_volume, fade_in=audio_fade_in, fade_out=audio_fade_out,
                    )
                _sz = os.path.getsize(output_path)
                results.append({"label": label, "success": True, "path": output_path, "size": _sz})
                job_history.append_job(job_history.make_record(
                    label=label, source_file=uploaded_file.name, output_path=output_path,
                    duration_seconds=secs, size_bytes=_sz,
                    preset_id=enc_preset_id, ar_id=ar_id, tab="single",
                ))
            except engine.AutoLoopError as e:
                results.append({"label": label, "success": False, "error": str(e)})
            progress_bar.progress(1.0)
        else:
            for i, batch_result in enumerate(
                engine.render_audio_batch(
                    effective_video_path, uploaded_file.name, audio_batch, OUTPUT_DIR,
                    volume=audio_volume, fade_in=audio_fade_in, fade_out=audio_fade_out,
                    output_ext=_out_ext,
                )
            ):
                status.write(f"Rendering {i + 1}/{len(audio_batch)}: **{batch_result.display_name}**")
                if batch_result.success:
                    results.append({"label": batch_result.display_name, "success": True,
                                     "path": batch_result.output_path, "size": batch_result.size_bytes})
                    job_history.append_job(job_history.make_record(
                        label=batch_result.display_name, source_file=uploaded_file.name,
                        output_path=batch_result.output_path,
                        duration_seconds=audio_batch[i].target_seconds,
                        size_bytes=batch_result.size_bytes,
                        preset_id=enc_preset_id, ar_id=ar_id, tab="single",
                    ))
                else:
                    results.append({"label": batch_result.display_name, "success": False,
                                     "error": batch_result.error})
                progress_bar.progress((i + 1) / len(audio_batch))

        status.empty()
        elapsed = time.time() - start
        succeeded = [r for r in results if r["success"]]
        failed = [r for r in results if not r["success"]]

        if succeeded:
            total_size = sum(r["size"] for r in succeeded)
            st.success(
                f"Finished {len(succeeded)}/{len(results)} in {elapsed:.1f}s. "
                f"Total output: {engine.format_bytes(total_size)}"
            )
        if failed:
            st.error(f"{len(failed)} file(s) failed to render.")

        for r in results:
            if not r["success"]:
                st.write(f"❌ **{r['label']}** — {r['error']}")
                continue

            st.write(f"✅ **{r['label']}** — {engine.format_bytes(r['size'])}")
            st.code(os.path.abspath(r["path"]))
            if r["size"] <= BROWSER_DOWNLOAD_LIMIT_BYTES:
                with open(r["path"], "rb") as f:
                    st.download_button(
                        f"Download {os.path.basename(r['path'])}",
                        data=f,
                        file_name=os.path.basename(r["path"]),
                        mime=_video_mime(r["path"]),
                        key=f"dl_{r['path']}",
                    )
            else:
                st.info(
                    f"Exceeds the in-browser download limit ({engine.format_bytes(BROWSER_DOWNLOAD_LIMIT_BYTES)}). "
                    "Grab it directly from the path above."
                )


