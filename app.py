            _step = 0.1 if _dur <= 60 else 0.5
            _max_v = float(int(_dur / _step) * _step)
            trim_range = st.slider(
                "Clip range",
                min_value=0.0, max_value=_max_v,
                value=(0.0, _max_v),
                step=_step, format="%.1fs",
            )
            trim_start, trim_end = float(trim_range[0]), float(trim_range[1])
            seg_dur = trim_end - trim_start

